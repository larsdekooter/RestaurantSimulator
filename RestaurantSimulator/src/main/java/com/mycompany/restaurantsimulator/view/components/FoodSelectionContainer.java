    /**
     * Repopulates the list
     * 
     * @param type
     */
    public void setFoodType(FoodType type) {
        this.foodType = type;
        menuItems.clear();
        for (Food item : this.menu.foods) {
            if (item.getFoodType() == type) {
                menuItems.add(item);
            }
        }
        updateList(menuItems);
    }

